# 설정
매달투자금액 = 50      # 만원
매달_이율 = 0.008      # 월 0.8%
투자기간 = 300         # 개월

입금금액 = 0           # 누적 원금(만원)
최종금액 = 0.0         # 평가금액(만원)

for month in range(1, 투자기간 + 1):
    # 월초 입금
    입금금액 += 매달투자금액
    최종금액 += 매달투자금액

    # 이 달 이자 계산(이윤) 후 반영
    월이자 = 최종금액 * 매달_이율
    최종금액 += 월이자

    # 누적 이자 = 평가금액 - 누적 입금
    누적이자 = 최종금액 - 입금금액

    print(f"{month}달: 누적입금 {입금금액}만원 | 월이자 {월이자:.1f}만원 | "
          f"누적이자 {누적이자:.1f}만원 | 평가금액 {최종금액:.1f}만원")
